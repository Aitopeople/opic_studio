const gradedTopics = VOCA_BOOKS.flatMap(({ words }) => words);
export const VOCA_TOPIC_WORDS = gradedTopics.map(
  ({ english, meaning, example, alternatives }) => ({
    english,
    meaning,
    example,
    alternatives,
  }),
);
export const VOCA_LEVEL_BOOKS = VOCA_BASIC_BOOKS.map(
  ({ grade, focus, words }) => ({
    grade,
    focus,
    words: [...words, ...gradedTopics.filter((word) => word.grade === grade)],
  }),
);
export const VOCA_WORDS: VocaWord[] = [
  ...VOCA_TOPIC_WORDS,
  ...VOCA_BASIC_BOOKS.flatMap(({ words }) => words),
];
