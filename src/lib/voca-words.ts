import { VOCA_BASIC_BOOKS } from "./voca-basics";
import type { VocaGrade } from "./voca-practice-entries";

export type VocaWord = {
  english: string;
  meaning: string;
  alternatives?: string[];
  example?: string;
};

// The first spelling is the one learners see in hints and feedback.
function book<T extends string>(
  id: T,
  title: string,
  entries: [string, VocaGrade, string, string, ...string[]][],
) {
  const words = entries.map(
    ([english, grade, meaning, example, ...alternatives]) => ({
      english,
      grade,
      meaning,
      example,
      alternatives,
    }),
  );
  return { id, title, words };
}

